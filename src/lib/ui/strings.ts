export type StringKey = keyof typeof en;
export type Translate = (key: StringKey) => string;
export type Locale = 'en' | 'sq';

// Fillon me anglisht (edhe gjatë render-it në server) dhe kalon në shqip pas ngarkimit
// nëse shfletuesi është në shqip — kështu HTML i serverit dhe i klientit përputhen.
export function useStrings(): { t: Translate; locale: Locale } {
  const [locale, setLocale] = useState<Locale>('en');
  useEffect(() => {
    if (navigator.language.toLowerCase().startsWith('sq')) setLocale('sq');
  }, []);
  // `t` mbetet e njëjta midis render-ave: përdoret si varësi në useCallback/useEffect.
  const t = useCallback<Translate>((key) => (locale === 'sq' ? sq : en)[key], [locale]);
  return useMemo(() => ({ t, locale }), [t, locale]);
}
